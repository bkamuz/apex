"""Regenerate apps/web/src/tools/iconCatalog.generated.ts from the Poché sources.

    python3 scripts/icons/generate.py            # write the TS catalog
    python3 scripts/icons/generate.py --svg DIR  # also write DIR/{16,24,32}/[genus-editor/]<id>.svg
    python3 scripts/icons/generate.py --check    # exit 1 if the catalog is out of date

Standard library only.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import engine  # noqa: E402
import poche  # noqa: E402
from meta import FUTURE, GENUS, GENUS_ALIAS, MAIN  # noqa: E402

OUT = os.path.join(HERE, '..', '..', 'src', 'tools', 'iconCatalog.generated.ts')


def glyph(key, px):
    uid = key.replace('ge:', 'ge-')
    return engine.render(uid, poche.draw(key), px, 'p')


def catalog():
    """{(kind, id, px): svg} for every shipped file; genus aliases are not duplicated."""
    out = {}
    for iid, *_ in MAIN + FUTURE:
        for px in engine.SIZES:
            out[('main', iid, px)] = glyph(iid, px)
    for gid, *_ in GENUS:
        if gid in GENUS_ALIAS:
            continue
        for px in engine.SIZES:
            out[('genus', gid, px)] = glyph('ge:' + gid, px)
    return out


def ts_block(name, kind, ids, svgs):
    lines = [f'export const {name}: Readonly<Record<ToolIconSize, Readonly<Record<string, string>>>> = {{']
    for px in engine.SIZES:
        lines.append(f'  {px}: {{')
        for i in ids:
            svg = svgs[(kind, i, px)].replace(' aria-hidden="true"', '')
            lines.append(f'    {json.dumps(i)}: {json.dumps(svg, ensure_ascii=False)},')
        lines.append('  },')
    lines.append('};')
    return '\n'.join(lines)


def typescript(svgs):
    main_ids = [i for i, *_ in MAIN + FUTURE]
    genus_ids = [g for g, *_ in GENUS if g not in GENUS_ALIAS]
    return '\n'.join([
        '// Generated by scripts/icons/generate.py (Poché icon set) — do not edit by hand.',
        '// Two tones only: currentColor and currentColor at 40 % opacity; #000/#fff appear inside masks only.',
        '// Mask ids use the `apx-p-` prefix; `scopeSvgIds` makes them unique per rendered instance.',
        '',
        'export type ToolIconSize = 16 | 24 | 32;',
        '',
        'export const TOOL_ICON_SIZES: readonly ToolIconSize[] = [16, 24, 32];',
        '',
        ts_block('TOOL_ICON_SVG', 'main', main_ids, svgs),
        '',
        '/** Genus editor ribbon glyphs that are not shared with the main ribbon. */',
        ts_block('GENUS_ICON_SVG', 'genus', genus_ids, svgs),
        '',
        '/** Genus editor ids drawn with a main-ribbon glyph. */',
        'export const GENUS_ICON_ALIAS: Readonly<Record<string, string>> = ' + json.dumps(GENUS_ALIAS, indent=2) + ';',
        '',
    ])


def write_svgs(svgs, root):
    for (kind, iid, px), svg in svgs.items():
        d = os.path.join(root, str(px), 'genus-editor' if kind == 'genus' else '')
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, f'{iid}.svg'), 'w', encoding='utf-8') as f:
            f.write(svg)


def main(argv):
    svgs = catalog()
    src = typescript(svgs)
    if '--check' in argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != src:
            print('iconCatalog.generated.ts is out of date: run npm run icons:generate', file=sys.stderr)
            return 1
        print('iconCatalog.generated.ts is up to date')
        return 0
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(src)
    if '--svg' in argv:
        write_svgs(svgs, argv[argv.index('--svg') + 1])
    print(f'wrote {os.path.relpath(OUT)} ({len(svgs)} glyphs)')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
